    for row in rows:
        assert_public(dict(zip(DICTIONARY_HEADERS, row)), known_secrets=known_secrets)
    print("All security assertions passed! Zero Level-A secrets and zero leaked PII.")

    # 3. Connect to private store
    store = PrivateSheetStore()
    ss = store.spreadsheet
    ws = ss.worksheet('DATA_DICTIONARY')

    # Ensure worksheet dimension
    req_rows = len(rows) + 10
    req_cols = len(DICTIONARY_HEADERS)
    if ws.row_count < req_rows or ws.col_count < req_cols:
        print(f"Resizing DATA_DICTIONARY to {req_rows} rows x {req_cols} cols...")
        store._write(ws.resize, rows=max(req_rows, ws.row_count), cols=max(req_cols, ws.col_count))

    # Clear old filter before writing if any exists
    try:
        store._write(ws.clear_basic_filter)
    except Exception:
        pass

    # 4. Write new schema header and data rows in chunks
    end_col = column_name(len(DICTIONARY_HEADERS))
    all_values = [DICTIONARY_HEADERS] + rows
    print(f"Writing {len(all_values)} rows to DATA_DICTIONARY...")
    
    # Write in batches of 100 rows
    batch_size = 100
    for start in range(0, len(all_values), batch_size):
        chunk = all_values[start:start + batch_size]
        range_name = f"A{start + 1}:{end_col}{start + len(chunk)}"
        print(f"  Writing rows {start + 1} to {start + len(chunk)}...")
        store._write(ws.update, range_name=range_name, values=chunk, value_input_option='RAW')

    # Clear any residual rows if previous sheet had more rows than current
    if ws.row_count > len(all_values):
        trailing_start = len(all_values) + 1
        trailing_end = ws.row_count
        empty_chunk = [[''] * len(DICTIONARY_HEADERS) for _ in range(trailing_end - trailing_start + 1)]
