def run_semantic_regression_audit(rows):
    """
    Automated regression checks to prevent analytical and privacy contract drift:
    1. Every row has exactly 15 columns.
    2. strong_shared definitions require distinct video_ids and never message/interaction counts.
    3. ARI does not claim statistical significance.
    4. HIGH evidence tier does not claim probability of truth or zero bias.
    5. HMAC is never described as decryptable.
    6. Comments are never equated with VOD viewing.
    7. viewer_hash counts are never labeled unique humans ('คน').
    8. weighted_degree is never described as traffic flow or migration.
    9. Dual population semantics for VIEWER_INDEX are documented.
    10. UNRESOLVED_HANDLE resolution policy is correctly restricted.
    """
    errors = []

    # 1. 15-column check
    for idx, row in enumerate(rows, 1):
        if len(row) != 15:
            errors.append(f"Row {idx} has {len(row)} columns; expected exactly 15.")

    # Forbidden phrases check across specific contexts
    for idx, row in enumerate(rows, 1):
        row_str = " ".join(str(c) for c in row)
        category = row[0]
        field = row[2]
        thai_name = row[3]
        def_th = row[4]
        calc = row[5]
        unit = row[6]
        warn = row[12]

        # 2. strong_shared check
        if 'strong_shared' in field.lower() or 'strong shared' in thai_name.lower():
            if 'video_id' not in row_str and 'วิดีโอ' not in row_str:
                errors.append(f"Row {idx} ({field}): strong_shared must explicitly mention distinct video_id / วิดีโอ.")
            if '>= 2 comments' in row_str.lower() or '>= 2 chat messages' in row_str.lower():
                errors.append(f"Row {idx} ({field}): strong_shared must NOT be defined as >=2 comments/messages.")

        # 3. ARI statistical significance check
        if field == 'ARI':
            if 'มีนัยสำคัญทางสถิติ' in row_str or 'statistically significant' in row_str.lower():
                errors.append(f"Row {idx} ({field}): ARI must NOT claim statistical significance / มีนัยสำคัญทางสถิติ.")
            if 'chance' not in row_str.lower() and 'ความบังเอิญ' not in row_str:
                errors.append(f"Row {idx} ({field}): ARI must state adjustment for chance / ปรับแก้ความบังเอิญ.")

        # 4. HIGH evidence tier check
        if field == 'HIGH' or (field == 'evidence_support_tier' and category == 'QUICK_REFERENCE_METRIC'):
            forbidden_tier_claims = ['ความจริงแน่นอน', 'probability of truth', 'guaranteed reliable', 'ปราศจากอคติ', 'very low bias', 'ไม่มีความเสี่ยงต่ออคติ']
            for claim in forbidden_tier_claims:
                if claim in row_str.lower():
                    errors.append(f"Row {idx} ({field}): Evidence tier must NOT claim '{claim}'.")

        # 5. HMAC decryption check
        if field == 'viewer_hash':
            if 'ถอดรหัส' in row_str and 'ไม่สามารถถอดรหัส' not in row_str:
                errors.append(f"Row {idx} ({field}): HMAC must NOT be described as decryptable.")
            if 'กุญแจถอดรหัส' in row_str and 'ไม่ใช่กุญแจถอดรหัส' not in row_str:
                errors.append(f"Row {idx} ({field}): Secret key must NOT be called a decryption key.")

        # 6. Comment viewing claim check
        if 'comment' in field.lower() and ('ดูคลิปย้อนหลัง' in row_str or 'vod viewing' in row_str.lower()):
            if 'ไม่ใช่วัดการรับชม' not in row_str and 'ไม่ได้พิสูจน์การดูคลิปย้อนหลัง' not in row_str and 'ไม่ใช่การวัดการรับชมคลิปย้อนหลัง' not in row_str:
                errors.append(f"Row {idx} ({field}): Comments must NOT be equated with VOD viewing proof.")

        # 7. Unit check: viewer_hash counts must not be labeled unique humans ('คน')
        if any(v in field.lower() for v in ['shared_any', 'strong_shared', 'total_interactions', 'subscriber_count']):
            if unit.strip() == 'Integer (คน)' or unit.strip() == 'Integer (จำนวนบัญชี/คน)':
                errors.append(f"Row {idx} ({field}): Unit must NOT be 'Integer (คน)'; use 'Integer (บัญชี/รหัสนามแฝงที่สังเกตพบ)'.")

        # 8. weighted_degree check
        if field == 'weighted_degree':
            for bad_term in ['traffic flow', 'viewer movement', 'audience exchange', 'การเคลื่อนย้ายคนดู', 'การไหลเวียนของผู้ชม']:
                if bad_term in def_th.lower() or bad_term in calc.lower():
                    errors.append(f"Row {idx} ({field}): weighted_degree must NOT be defined as '{bad_term}'.")

        # 9. Non-neutral terms check in definitions and calculations
        for bad_word in ['แฟนคลับตัวจริง', 'แฟนเหนียวแน่น', 'ความภักดี', 'agency-locked audience']:
            if bad_word in def_th or bad_word in calc:
                errors.append(f"Row {idx} ({field}): Found non-neutral term '{bad_word}' in definition/calc.")

        # 10. UNRESOLVED_HANDLE resolution policy
        if field == 'UNRESOLVED_HANDLE':
            if 'เดา' not in row_str or 'authoritative' not in row_str.lower():
                errors.append(f"Row {idx} ({field}): UNRESOLVED_HANDLE must state resolution policy via authoritative public metadata and forbid guessing.")

        # 11. Residual observational / stream language check
        if 'สายดูสด' in row_str:
            errors.append(f"Row {idx} ({field}): Residual phrase 'สายดูสด' must NOT be used.")

        # 12. VIEWER_INDEX reconciliation status check
        if 'หลังการกระทบยอด' in row_str:
            errors.append(f"Row {idx} ({field}): 'หลังการกระทบยอด' must NOT be used; VIEWER_INDEX is Master Identity Candidate Index Pending Cross-Namespace Reconciliation.")
        if 'reconciled identity' in row_str.lower() and 'candidate' not in row_str.lower():
            errors.append(f"Row {idx} ({field}): 'Reconciled Identity' must NOT be used without specifying Candidate.")

        # 13. total_interactions temporal regularity check
        if field == 'total_interactions' and row[1] == 'VIEWER_INDEX':
            if 'สม่ำเสมอ' in row[8]:  # high_value_means
                errors.append(f"Row {idx} ({field}): high_value_means must NOT claim 'สม่ำเสมอ' solely from high count.")

    if errors:
        raise AssertionError(f"Semantic Regression Audit FAILED with {len(errors)} errors:\n" + "\n".join(f"- {e}" for e in errors))
    print(f"Semantic Regression Audit PASSED! Validated all {len(rows)} dictionary rows against analytical & privacy contracts.")

